r = await registar(falhado())
let s = await ler(dono)
ok(r.estado === 'ok' && r.mudou === null && s.aConfirmar === true, 'uma sonda má só fica "a confirmar": o estado não muda')
ok((await raiz(`select count(*)::int as n from saude_incidentes`))[0].n === 0, 'e não abre incidente')
r = await registar(falhado())
s = await ler(dono)
ok(r.estado === 'em_baixo' && r.mudou === 'abriu' && s.estado === 'em_baixo' && s.aConfirmar === false, 'à segunda seguida confirma: em baixo, e abre o incidente')
ok(codigos(r).join() === 'monitor_em_baixo:site' && r.motivos[0].detalhe === 'HTTP 502', 'o motivo diz que sonda caiu e porquê')
ok(s.incidentes.length === 1 && s.incidentes[0].fim === null && s.incidentes[0].estado === 'em_baixo' && s.desde !== null, 'há um incidente aberto, com o início')
const inicioIncidente = new Date(s.incidentes[0].inicio).getTime()
const primeiraMa = new Date((await raiz(`select em from saude_amostras where estado_instante <> 'ok' order by em limit 1`))[0].em).getTime()
ok(Math.abs(inicioIncidente - primeiraMa) < 2, 'o incidente começa na primeira amostra má (não na que o confirmou)')
r = await registar(falhado())
ok(r.mudou === null && r.estado === 'em_baixo', 'a seguir, continua em baixo sem abrir outro')
ok((await raiz(`select count(*)::int as n from saude_incidentes`))[0].n === 1, 'um só incidente')

console.log('\nRecuperar (três boas seguidas)')
