ok(s.incidentes.length === 1 && s.incidentes[0].estado === 'sobrecarga' && s.incidentes[0].motivos.length === 1 && s.incidentes[0].motivos[0].valor === 5000, 'o incidente guarda o pior estado e o pior valor de cada motivo')
