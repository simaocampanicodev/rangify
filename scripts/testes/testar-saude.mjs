ok(a1.agora.ligacoesMax > 0 && a1.agora.ligacoes <= a1.agora.ligacoesMax && a1.agora.partidasParadas === 0 && a1.agora.cpu === null, 'mostra as ligações (o limite do servidor) e as partidas; a CPU fica vazia (o servidor não deu métricas)')
ok(a1.semSondas === true && a1.serie.length === 1, 'continua a dizer que não há sondas, e a série já tem um ponto')

